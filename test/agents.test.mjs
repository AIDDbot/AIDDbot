// End-to-end tests of the aidd core: the form of each AGENTS.md and the index of each shared folder.
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { test } from "node:test";
import { git, write, repo, aidd, accept, approve } from "./helpers.mjs";

const ROOT_AGENTS = ["# Project instructions", "", "## Assistant", "", "- Ask one closed question.", "", "## System", "", "| Project | Type |", "| --- | --- |", "| back | api |", "", "## Commands", "", "- `npm test`", "", "## Records", "", "- Specs in `.product/specs/`.", "", "## Git", "", "- Conventional commits.", ""].join("\n");
const PROJECT_AGENTS = ["# back — api", "", "## Purpose", "", "- **Owns**: the API.", "", "## Technology", "", "- Express.", "", "## Folders", "", "| Concept | Path |", "| --- | --- |", "| core | `src/core/` |", "", "## Platform", "", "- **Port**: `PORT` = 3000", ""].join("\n");

function project(root) {
  aidd(root, "config", "set", "projects.back", JSON.stringify({ type: "api", path: "back", commands: { test: "node -e 0" } }));
}

test("agents check passes a root and a project AGENTS.md in form, with no optional section", () => {
  const root = repo();
  project(root);
  write(root, "AGENTS.md", ROOT_AGENTS);
  write(root, "back/AGENTS.md", PROJECT_AGENTS);
  const checked = aidd(root, "agents", "check");
  assert.equal(checked.code, 0, JSON.stringify(checked.body));
  assert.deepEqual(checked.body.problems, []);
});

test("agents check names each problem: size, a comment, an empty table, an unknown, a missing and a misplaced section", () => {
  const root = repo();
  project(root);
  const long = ROOT_AGENTS.replace("- Ask one closed question.", Array.from({ length: 130 }, (_, i) => `- Rule ${i}.`).join("\n"));
  write(root, "AGENTS.md", long.replace("## Commands", "<!-- fill -->\n## Commands"));
  const misshaped = ["# back — api", "## Connections", "- front.", "## Purpose", "- **Owns**: the API.", "## Platform", "- **Port**: 3000", "## Technology", "| Slot | Command |", "| --- | --- |", "## Folders", "- `src/core/`"];
  write(root, "back/AGENTS.md", `${misshaped.join("\n")}\n`);
  const checked = aidd(root, "agents", "check");
  assert.equal(checked.code, 1);
  const error = checked.body.error;
  assert.match(error, /AGENTS\.md: \d+ lines, more than 128/);
  assert.match(error, /AGENTS\.md: a comment of the template is left/);
  assert.match(error, /back\/AGENTS\.md: unknown section "Connections"/);
  assert.match(error, /back\/AGENTS\.md: empty section "Technology"/, "a table with a header and no row is empty");
  assert.match(error, /back\/AGENTS\.md: sections out of order/);
  assert.doesNotMatch(error, /missing section "Platform"/, "Platform is there, only out of order");
  write(root, "back/AGENTS.md", PROJECT_AGENTS.replace(/## Platform[\s\S]*$/, ""));
  assert.match(aidd(root, "agents", "check").body.error, /back\/AGENTS\.md: missing section "Platform"/);
});

test("agents index writes each file of shared with its exports, and no test; an e2e has shared at its root", () => {
  const root = repo();
  project(root);
  aidd(root, "config", "set", "projects.e2e", JSON.stringify({ type: "e2e", path: "e2e", commands: { test: "node -e 0" } }));
  write(root, "e2e/shared/values/values.check.ts", "export const isText = (value: unknown): boolean => typeof value === \"string\";\n");
  write(root, "back/src/shared/values/text/text.parse.ts", "export function requireText(value: unknown): string {\n  return String(value);\n}\nexport const optionalText = (value: unknown): string | undefined => undefined;\nfunction hidden(): void {}\n");
  write(root, "back/src/shared/values/text/text.parse.test.ts", "export const fixture = 1;\n");
  write(root, "back/src/shared/state/store.create.ts", "export type Listener = () => void;\nexport interface Store {}\nexport async function createStore(): Promise<void> {}\nconst a = 1;\nconst b = 2;\nexport { a, b as other };\n");
  write(root, "back/src/shared/identity.type.ts", "type Local = string;\n");
  const indexed = aidd(root, "agents", "index");
  assert.equal(indexed.code, 0, JSON.stringify(indexed.body));
  assert.deepEqual(indexed.body.written, ["back/src/shared/README.md", "e2e/shared/README.md"]);
  assert.match(fs.readFileSync(path.join(root, "e2e/shared/README.md"), "utf8"), /\| `values\/values\.check\.ts` \| `isText` \|/);
  const text = fs.readFileSync(path.join(root, "back/src/shared/README.md"), "utf8");
  assert.match(text, /Generated by `aidd release`; do not edit\./);
  assert.match(text, /\| `state\/store\.create\.ts` \| `Listener`, `Store`, `createStore`, `a`, `other` \|/);
  assert.match(text, /\| `values\/text\/text\.parse\.ts` \| `requireText`, `optionalText` \|/);
  assert.doesNotMatch(text, /hidden|fixture|identity\.type/, "no private name, no test and no file without an export");
  assert.ok(text.indexOf("state/") < text.indexOf("values/"), "the files are in order");
});

test("release refuses an AGENTS.md out of form, and writes the index of shared when it ships", () => {
  const root = repo();
  project(root);
  write(root, "AGENTS.md", ROOT_AGENTS);
  write(root, "back/AGENTS.md", `${PROJECT_AGENTS}<!-- left -->\n`);
  write(root, "back/src/shared/values/values.check.ts", "export const isMissing = (value: unknown): boolean => value == null;\n");
  git(root, "add", "-A");
  git(root, "commit", "-q", "-m", "chore: back");
  aidd(root, "spec", "new", "fix", "crash", "Crash");
  approve(root);
  accept(root, 0, "S0001");
  aidd(root, "eval", "verification", "green", "ok");
  aidd(root, "eval", "qualification", "green", "ok");
  const refused = aidd(root, "release");
  assert.equal(refused.code, 1);
  assert.match(refused.body.error, /S0001 cannot ship: AGENTS\.md has 1 problem\(s\): back\/AGENTS\.md: a comment of the template is left/);
  write(root, "back/AGENTS.md", PROJECT_AGENTS);
  git(root, "add", "-A");
  git(root, "commit", "-q", "-m", "fix(back): form of AGENTS.md");
  aidd(root, "run", "test", "--project", "e2e");
  const shipped = aidd(root, "release");
  assert.equal(shipped.code, 0, JSON.stringify(shipped.body));
  assert.deepEqual(shipped.body.shared, ["back/src/shared/README.md"]);
  assert.match(git(root, "show", "--name-only", "--format=", "HEAD^2"), /back\/src\/shared\/README\.md/, "the release commit has the index");
});
